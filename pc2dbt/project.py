"""Write: the dbt project on disk (models, sources.yml, dbt_project.yml) and the flags report."""
from __future__ import annotations

import re
from dataclasses import dataclass, field
from pathlib import Path

from .convert import Flag, Model, convert_mapping, lines, written_tables
from .parse import Folder, parse_file
from .types import duck_type


@dataclass
class LeftOut:
    what: str
    line: int
    why: str


@dataclass
class Report:
    models: list[Model]
    flags: list[tuple[str, Flag]]          # (model name, flag)
    left_out: list[LeftOut]
    exit_code: int = 0


def project_name(folder: Folder) -> str:
    name = re.sub(r"[^a-z0-9_]", "_", folder.name.lower())
    return name if name[:1].isalpha() else f"p_{name}"


def yaml_quote(text: str) -> str:
    return "'" + text.replace("'", "''") + "'"


def sources_yml(folder: Folder, used: set[tuple[str, str]]) -> str:
    by_owner: dict[str, list] = {}
    for key in sorted(used):
        table = folder.sources[key]
        by_owner.setdefault(table.owner.lower(), []).append(table)
    out = ["version: 2", "", "sources:"]
    for owner, tables in sorted(by_owner.items()):
        out += [f"  - name: {owner}", f"    schema: {owner}", "    tables:"]
        for t in tables:
            out += [f"      - name: {t.name.lower()}",
                    f"        description: {yaml_quote(f'PC Source {t.name} ({lines(t.line, t.end)}), owner {t.owner}')}",
                    "        columns:"]
            for f in t.fields.values():
                out += [f"          - name: {f.name.lower()}", f"            data_type: {duck_type(f.datatype, f.precision, f.scale)}"]
    return "\n".join(out) + "\n"


def left_out_items(folder: Folder, mapping_names: list[str]) -> list[LeftOut]:
    items = []
    for name in mapping_names:
        m = folder.mappings[name]
        for inst in m.instances.values():
            if inst.type == "TARGET":
                for attr in ("Pre SQL", "Post SQL"):
                    value, line = inst.attributes.get(attr, ("", 0))
                    if value.strip():
                        items.append(LeftOut(f"{attr} on target {inst.name}: {value}", line,
                                             "a dbt table is rebuilt on every run (decision Q9)"))
    for wf in folder.root.iter("WORKFLOW"):
        items.append(LeftOut(f"Workflow {wf.get('NAME')} (run order, links and failure handling)", wf.line,
                             "dbt orders models from ref(); behaviour on failure is out of scope (decisions Q5, Q17)"))
        for task in wf.kids("TASK"):  # the workflow's own tasks, not helpers inside sessions
            if task.get("TYPE") == "Command":
                items.append(LeftOut(f"Command task {task.get('NAME')} (its command is never read)", task.line,
                                     "not part of any mapping (decision Q17)"))
    for session in folder.root.iter("SESSION"):
        if session.get("MAPPINGNAME") in mapping_names:
            items.append(LeftOut(f"Session {session.get('NAME')} (connections and load settings)", session.line,
                                 "connections come from the dbt profile; load settings from materialization (decision Q17)"))
    return items


def flags_md(xml_name: str, report: Report) -> str:
    out = [f"# Flags for {xml_name}", "",
           "Behaviour copied from the XML as-is (decision D1), and what the converter left out.",
           "Line numbers refer to the PowerCenter XML.", "", "## Flags", ""]
    if not report.flags:
        out.append("None.")
    for model in report.models:
        mine = [f for m, f in report.flags if m == model.name]
        if mine:
            out += [f"### {model.folder}/{model.name}", ""]
            out += [f"- **{f.kind}** L{f.line}: {f.message}" for f in sorted(mine, key=lambda f: (f.line, f.kind))]
            out.append("")
    out += ["## Left out", ""]
    out += [f"- L{i.line}: {i.what}. Why: {i.why}." for i in report.left_out] or ["Nothing."]
    return "\n".join(out) + "\n"


def write_project(xml_path, out_dir, mappings: list[str] | None = None) -> Report:
    xml_path, out = Path(xml_path), Path(out_dir)
    folder = parse_file(xml_path)
    names = mappings or list(folder.mappings)
    models: list[Model] = []
    for name in names:
        models.extend(convert_mapping(folder, name))
    report = Report(models, [(m.name, f) for m in models for f in m.flags], left_out_items(folder, names))

    name = project_name(folder)
    (out / "models").mkdir(parents=True, exist_ok=True)
    (out / "dbt_project.yml").write_text(
        f"name: {name}\nversion: '1.0.0'\nconfig-version: 2\nprofile: {name}\nmodel-paths: ['models']\n\n"
        f"# Generated by pc2dbt from {xml_path.name}. Every model is a table rebuilt on each run (decision Q9).\n"
        f"models:\n  {name}:\n    +materialized: table\n")
    used = set()
    for m in models:
        target_dir = out / "models" / m.folder
        target_dir.mkdir(parents=True, exist_ok=True)
        (target_dir / f"{m.name}.sql").write_text(m.sql)
    written = written_tables(folder)  # read with ref(), so not a dbt source (decision Q5)
    for mname in names:
        mp = folder.mappings[mname]
        used |= {(i.dbd, i.definition) for i in mp.instances.values() if i.type == "SOURCE" and i.definition not in written}
    (out / "models" / "sources.yml").write_text(sources_yml(folder, used))
    (out / "flags.md").write_text(flags_md(xml_path.name, report))
    return report

"""Build docs/assets/example-output.js: what pc2dbt wrote for the orders path on the "One mapping, end to end" page.

The page shows the generated files word for word, never a hand-written copy:
  - stg_orders.sql exactly as `pc2dbt convert` wrote it into out/
  - the raw_orders entry of out/models/sources.yml
  - one real row (the first order in raw_orders.csv) from our build and from jaffle-shop's, as
    written by tests/test_reference_staging.py into tests/reference/results/example_row.json,
    and the staging comparison summary from staging.json next to it

tests/test_docs_fresh.py fails when this file no longer matches out/ or the last reference run.

Usage (from the repo root): python3 -I tools/docs/build_example_output.py out tests/reference/results/example_row.json docs/assets/example-output.js
"""
import json
import sys
from pathlib import Path

out_dir, row_path, out_path = (Path(a) for a in sys.argv[1:4])
SQL_PATH = "out/models/m_fl_js_staging_full/stg_orders.sql"

sql = (out_dir / "models" / "m_fl_js_staging_full" / "stg_orders.sql").read_text(encoding="utf-8")
yml = (out_dir / "models" / "sources.yml").read_text(encoding="utf-8")

lines = yml.splitlines(keepends=True)
head_end = next(i for i, l in enumerate(lines) if l.strip() == "tables:") + 1
start = next(i for i, l in enumerate(lines) if l.rstrip() == "      - name: raw_orders")
end = next((i for i in range(start + 1, len(lines)) if lines[i].startswith("      - name: ")), len(lines))
names = [l.split("- name: ")[1].strip() for l in lines if l.startswith("      - name: ")]

data = {
    "sql_path": SQL_PATH,
    "sql": sql,
    "sources_head": "".join(lines[:head_end]),
    "sources": "".join(lines[start:end]),
    "tables_before": names[:names.index("raw_orders")],
    "tables_after": names[names.index("raw_orders") + 1:],
    "row": json.loads(row_path.read_text(encoding="utf-8")),
    # the staging comparison with jaffle-shop, from the same reference run
    "staging_summary": json.loads((row_path.parent / "staging.json").read_text(encoding="utf-8"))["summary"],
}

with open(out_path, "w", encoding="utf-8") as f:
    f.write("/* GENERATED by tools/docs/build_example_output.py from out/ and tests/reference/results/example_row.json.\n")
    f.write("   Do not edit by hand. */\n")
    f.write("window.EXAMPLE_OUTPUT = ")
    f.write(json.dumps(data, ensure_ascii=False, indent=1))
    f.write(";\n")
print(f"{out_path}: {SQL_PATH} ({len(sql.splitlines())} lines), raw_orders source, row {data['row']['raw']['id'][:8]}")

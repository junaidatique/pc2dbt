"""Build docs/assets/results-data.js for the Results page.

One section per mapping. For each converted table: every box of the mapping as XML lines, next to
the SQL it became, plus the comparison with jaffle-shop from tests/reference/results/<section>.json.

Usage (from the repo root, with the project venv):
    .venv/bin/python tools/docs/build_results_data.py <xml> <out.js> <mapping>=<results.json>[+<facts.json>] [...]
"""
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
from pc2dbt.convert import convert_mapping  # noqa: E402
from pc2dbt.parse import parse_file  # noqa: E402

xml_path, out_path = sys.argv[1:3]
pairs = [a.split("=", 1) for a in sys.argv[3:]]
lines = Path(xml_path).read_text(encoding="utf-8", errors="replace").splitlines()
NOISE = re.compile(r'\s(DESCRIPTION|PICTURETEXT|OBJECTVERSION|VERSIONNUMBER|REUSABLE|BUSINESSNAME|FIELDNUMBER|FIELDPROPERTY|'
                   r'FIELDTYPE|HIDDEN|LENGTH|LEVEL|OCCURS|OFFSET|PHYSICALLENGTH|PHYSICALOFFSET|USAGE_FLAGS|'
                   r'SHIFTSENSITIVE|MAPPLETGROUP|SORTDIRECTION|KEYTYPE|NULLABLE|EXPRESSIONTYPE)\s*="[^"]*"')
SKIP = re.compile(r'<TABLEATTRIBUTE NAME ="(Tracing Level|Sorter Cache Size|Aggregator Data Cache Size|Aggregator Index Cache Size|Work Directory|Merge Only|Partitioning|'
                  r'Transformation Scope|Null Treated Low|Case Sensitive|Is Partitionable|Pre SQL|Post SQL|Sql Query|'
                  r'User Defined Join|Source Filter|Number Of Sorted Ports|Output is deterministic|Output is repeatable|'
                  r'Cache Directory|Joiner Data Cache Size|Joiner Index Cache Size|Sorted Input|Master Sort Order|'
                  r'Language|Module Identifier|Class Name|Function Identifier|Runtime Location|Inputs Must Block|'
                  r'Is Active|Update Strategy Transformation|Generate Transaction|Output Is Repeatable|'
                  r'Requires Single Thread Per Partition|Output Is Deterministic|Preserves Data Set Boundary)"|'
                  r'<INITPROP |<FIELDDEPENDENCY ')


def excerpt(start: int, end: int) -> list:
    out = []
    for n in range(start, end + 1):
        text = lines[n - 1]
        if "VALUEPAIR" in text:
            raise SystemExit(f"refusing to copy credential line L{n}")
        if SKIP.search(text):
            continue
        out.append([n, NOISE.sub("", text.strip()).replace(" =", "=")])
    return out


folder = parse_file(xml_path)
sections, reference = [], ""
for mapping_name, paths in pairs:
    results_path, _, facts_path = paths.partition("+")
    mapping = folder.mappings[mapping_name]
    results = json.loads(Path(results_path).read_text())
    facts = json.loads(Path(facts_path).read_text()) if facts_path else []
    reference = results["reference"]
    by_table = {t["table"]: t for t in results["tables"]}
    tables = []
    for model in convert_mapping(folder, mapping_name):
        blocks = []
        for b in model.blocks:
            xml = excerpt(b.start, b.end)
            if b.kind == "Target":
                xml += [[c.line, NOISE.sub("", lines[c.line - 1].strip()).replace(" =", "=")]
                        for c in mapping.connectors if c.to_instance == model.target]
            blocks.append({"box": b.box, "kind": b.kind, "lines": [b.start, b.end], "note": b.note, "xml": xml, "sql": b.sql})
        tables.append({"name": model.name, "target": model.target, "folder": model.folder,
                       "flags": [{"kind": f.kind, "line": f.line, "message": f.message} for f in model.flags],
                       "blocks": blocks, "comparison": by_table.get(model.name)})
    sections.append({"mapping": mapping_name, "mapping_lines": [mapping.line, mapping.end],
                     "summary": results["summary"], "tables": tables, "facts": facts})

data = {"xml": Path(xml_path).name, "reference": reference, "sections": sections}
js = "/* GENERATED by tools/docs/build_results_data.py. Do not edit by hand. */\nwindow.RESULTS = " + \
     json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n"
assert "VALUEPAIR" not in js
Path(out_path).write_text(js, encoding="utf-8")
print(f"OK: {len(sections)} sections, {sum(len(x['tables']) for x in sections)} tables, "
      f"{sum(len(t['blocks']) for x in sections for t in x['tables'])} boxes, {len(js) // 1024} KB")
